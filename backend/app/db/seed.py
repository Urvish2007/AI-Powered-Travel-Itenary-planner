async def seed_places(*, embed: bool = True) -> int:
    """Insert the place corpus. Existing places are left alone.

    Returns the number of places inserted.
    """
    from slugify import slugify

    from app.ai.embeddings import embed_text, place_embedding_text
    from app.core.config import settings
    from app.models.base import GeoPoint

    inserted = 0
    for row in ALL_SEED_PLACES:
        slug = slugify(f"{row['name']}-{row['city']}")[:280]
        if await Place.find_one(Place.slug == slug) is not None:
            continue

        place = Place(
            name=row["name"],
            slug=slug,
            description=row["description"],
            category=row["category"],
            tags=row["tags"],
            location=GeoPoint.from_lat_lng(row["lat"], row["lng"]),
            city=row["city"],
            country=row["country"],
            timezone=row["timezone"],
            rating=row["rating"],
            review_count=int(row["popularity"] * 50_000),
            popularity=row["popularity"],
            average_visit_minutes=row["minutes"],
            cost=PlaceCost(amount=row["cost"], currency=row["currency"]),
            opening_hours=[OpeningHours(**h) for h in row["hours"]],
            wheelchair_accessible=row["accessible"],
            family_friendly=row["family"],
            source="seed",
        )
        if embed:
            place.embedding = await embed_text(
                place_embedding_text(
                    place.name,
                    place.description,
                    str(place.category),
                    [str(t) for t in place.tags],
                    place.city,
                )
            )
            place.embedding_model = settings.embedding_model

        await place.insert()
        inserted += 1

    logger.info("places_seeded", inserted=inserted, total=len(ALL_SEED_PLACES))
    return inserted


async def seed_users() -> int:
    """Create the demo and admin accounts if they do not already exist."""
    created = 0
    for row in DEMO_USERS:
        if await User.find_one(User.email == row["email"]) is not None:
            continue
        await User(
            email=row["email"],
            full_name=row["full_name"],
            hashed_password=hash_password(row["password"]),
            role=row["role"],
            home_city=row["home_city"],
            preferences=row["preferences"],
            is_verified=True,
        ).insert()
        created += 1

    logger.info("users_seeded", created=created)
    return created


async def seed_all(*, embed: bool = True) -> dict[str, int]:
    return {
        "users": await seed_users(),
        "places": await seed_places(embed=embed),
    }
