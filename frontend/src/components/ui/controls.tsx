// ---------------------------------------------------------------------------
// Avatar
// ---------------------------------------------------------------------------

export function Avatar({
  src,
  name,
  size = 40,
  className,
}: {
  src?: string | null;
  name: string;
  size?: number;
  className?: string;
}) {
  return (
    <AvatarPrimitive.Root
      className={cn(
        "relative flex shrink-0 overflow-hidden rounded-full bg-primary-soft",
        className,
      )}
      style={{ width: size, height: size }}
    >
      {src && (
        <AvatarPrimitive.Image
          src={src}
          alt=""
          className="size-full object-cover"
          // Radix swaps to the fallback automatically if this errors, so a
          // broken provider avatar never leaves an empty circle.
          referrerPolicy="no-referrer"
        />
      )}
      <AvatarPrimitive.Fallback
        className="flex size-full items-center justify-center font-semibold text-primary"
        style={{ fontSize: Math.max(11, size * 0.38) }}
        delayMs={src ? 300 : 0}
      >
        {toInitials(name)}
      </AvatarPrimitive.Fallback>
    </AvatarPrimitive.Root>
  );
}
